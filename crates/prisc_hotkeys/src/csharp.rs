//! Generates the C# mirror of the key table (`HotkeyKey.g.cs`, public, in Prisc.Shared) and of
//! the C ABI's constants and event struct (`HotkeysAbi.g.cs`, internal, in Prisc.Ui), and checks
//! that the checked-in files are current. Regenerate with
//! `PRISC_HOTKEYS_REGEN=1 cargo test -p prisc_hotkeys csharp_mirror`.

use std::fmt::Write as _;

use crate::ffi::{abi_version, ABI_CONSTS, EVENT_FIELDS};
use crate::{Key, Modifiers};

const KEYS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../ui/Prisc.Shared/Hotkeys/HotkeyKey.g.cs");
const ABI_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../ui/Prisc.Ui/Services/Hotkeys/HotkeysAbi.g.cs");

fn header(out: &mut String, source: &str) {
    out.push_str("// <auto-generated>\n");
    let _ = writeln!(out, "// Generated by prisc_hotkeys (src/csharp.rs) from {source}.");
    out.push_str("// Do not edit. Regenerate: PRISC_HOTKEYS_REGEN=1 cargo test -p prisc_hotkeys csharp_mirror\n");
    out.push_str("// </auto-generated>\n");
}

fn render_keys() -> String {
    let mut out = String::new();
    header(&mut out, "the key table in crates/prisc_hotkeys/src/key.rs");
    out.push_str(
        r#"#nullable disable
using System;
using System.Collections.Generic;

namespace Prisc
{
    /// <summary>A key a global hotkey can name — the prisc_hotkeys key table (values are Avalonia 12.1.2's,
    /// so settings saved before this type existed load unchanged). Canonical names only; aliases and labels
    /// parse via <see cref="HotkeyKeys.TryParse"/>.</summary>
    public enum HotkeyKey
    {
"#,
    );
    for &key in Key::ALL {
        let _ = writeln!(out, "        {} = {},", key.name(), key as i32);
    }
    let _ = write!(
        out,
        r#"    }}

    /// <summary>Global hotkey modifiers (Avalonia KeyModifiers values). Meta = Win on Windows, Command on macOS.</summary>
    [Flags]
    public enum HotkeyModifiers
    {{
        None = 0,
        Alt = 1,
        Control = 2,
        Shift = 4,
        Meta = 8,
    }}

    /// <summary>Generated name tables for <see cref="HotkeyKey"/>.</summary>
    public static class HotkeyKeys
    {{
        /// <summary>prisc_hotkeys_abi_version() of the native library this mirror was generated with.</summary>
        public const uint AbiVersion = 0x{:08X}u;

        /// <summary>The canonical (serialized) name; the numeric value for an undefined one.</summary>
        public static string Name(HotkeyKey key) => key switch
        {{
"#,
        abi_version()
    );
    for &key in Key::ALL {
        let _ = writeln!(out, "            HotkeyKey.{0} => \"{0}\",", key.name());
    }
    out.push_str(
        r#"            _ => ((int)key).ToString(System.Globalization.CultureInfo.InvariantCulture),
        };

        /// <summary>The short display name ("PrtScr", "Del", "1", "Num7", "="); the canonical name when
        /// there is no shorter one. For labels only — settings store <see cref="Name"/>.</summary>
        public static string Label(HotkeyKey key) => key switch
        {
"#,
    );
    for &key in Key::ALL {
        if key.label() != key.name() {
            let _ = writeln!(out, "            HotkeyKey.{} => \"{}\",", key.name(), cs_escape(key.label()));
        }
    }
    out.push_str(
        r#"            _ => Name(key),
        };

        /// <summary>Canonical names, aliases and labels, case-insensitive. No numbers beyond the
        /// top-row digits' labels, no comma lists.</summary>
        public static bool TryParse(string name, out HotkeyKey key) => Names.TryGetValue(name?.Trim() ?? "", out key);

        /// <summary>A gesture's modifier part: the canonical names and the shorthands (Ctrl, Cmd, Win,
        /// Option, Super, …), case-insensitive. "None" adds nothing.</summary>
        public static bool TryParseModifier(string name, out HotkeyModifiers modifier) =>
            ModifierNames.TryGetValue(name?.Trim() ?? "", out modifier);

        private static readonly Dictionary<string, HotkeyModifiers> ModifierNames = new(StringComparer.OrdinalIgnoreCase)
        {
"#,
    );
    for &(name, modifier) in Modifiers::NAMES {
        let _ = writeln!(out, "            [\"{name}\"] = {},", cs_modifier(modifier));
    }
    out.push_str(
        r#"        };

        private static readonly Dictionary<string, HotkeyKey> Names = new(StringComparer.OrdinalIgnoreCase)
        {
"#,
    );
    for &key in Key::ALL {
        let _ = writeln!(out, "            [\"{0}\"] = HotkeyKey.{0},", key.name());
    }
    for &key in Key::ALL {
        for alias in key.aliases() {
            let _ = writeln!(out, "            [\"{alias}\"] = HotkeyKey.{},", key.name());
        }
    }
    for &key in Key::ALL {
        // a label that repeats the key's own name or alias (Return's "Enter") is already listed
        let label = key.label();
        let listed = std::iter::once(key.name())
            .chain(key.aliases().iter().copied())
            .any(|name| name.eq_ignore_ascii_case(label));
        if !listed {
            let _ = writeln!(out, "            [\"{}\"] = HotkeyKey.{},", cs_escape(label), key.name());
        }
    }
    out.push_str("        };\n    }\n}\n");
    out
}

/// A C# string literal's body.
fn cs_escape(text: &str) -> String {
    text.replace('\\', "\\\\")
        .replace('"', "\\\"")
}

/// The C# spelling of one modifier flag (or none).
fn cs_modifier(modifier: Modifiers) -> &'static str {
    match modifier {
        Modifiers::NONE => "HotkeyModifiers.None",
        Modifiers::ALT => "HotkeyModifiers.Alt",
        Modifiers::CONTROL => "HotkeyModifiers.Control",
        Modifiers::SHIFT => "HotkeyModifiers.Shift",
        Modifiers::META => "HotkeyModifiers.Meta",
        other => panic!("no C# name for the modifier combination {other:?}"),
    }
}

/// `raw_code` → `RawCode`.
fn pascal_case(name: &str) -> String {
    name.split('_')
        .map(|part| part[..1].to_ascii_uppercase() + &part[1..])
        .collect()
}

fn render_abi() -> String {
    let mut out = String::new();
    header(&mut out, "the C ABI in crates/prisc_hotkeys/src/ffi.rs");
    out.push_str(
        r#"using System.Runtime.InteropServices;

namespace Prisc.UI
{
    /// <summary>prisc_hotkeys return codes and event kinds.</summary>
    internal static class HotkeysAbi
    {
"#,
    );
    for (name, value) in ABI_CONSTS {
        let _ = writeln!(out, "        public const int {name} = {value};");
    }
    out.push_str(
        r#"    }

    /// <summary>PriscHotkeysEvent, as prisc_hotkeys_next_event fills it.</summary>
    [StructLayout(LayoutKind.Sequential)]
    internal struct HotkeyEventNative
    {
"#,
    );
    for (name, c_type) in EVENT_FIELDS {
        let cs_type = match *c_type {
            "uint32_t" => "uint",
            "int32_t" => "int",
            other => panic!("no C# type for {other}"),
        };
        let _ = writeln!(out, "        public {cs_type} {};", pascal_case(name));
    }
    out.push_str("    }\n}\n");
    out
}

#[test]
fn csharp_mirror_is_current() {
    let regen = std::env::var("PRISC_HOTKEYS_REGEN").as_deref() == Ok("1");
    for (path, rendered) in [(KEYS_PATH, render_keys()), (ABI_PATH, render_abi())] {
        if regen {
            let path = std::path::Path::new(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, rendered).unwrap();
            continue;
        }
        let on_disk = std::fs::read_to_string(path)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        assert_eq!(
            on_disk, rendered,
            "{path} is stale: run PRISC_HOTKEYS_REGEN=1 cargo test -p prisc_hotkeys csharp_mirror"
        );
    }
}

#[test]
fn rendered_shapes() {
    let keys = render_keys();
    assert!(keys.contains("        PrintScreen = 30,\n"));
    assert!(keys.contains("            HotkeyKey.Oem3 => \"Oem3\",\n"));
    assert!(keys.contains("            [\"Snapshot\"] = HotkeyKey.PrintScreen,\n"));
    assert!(keys.contains("            [\"PrtScr\"] = HotkeyKey.PrintScreen,\n"));
    assert!(keys.contains("            HotkeyKey.D1 => \"1\",\n"));
    assert!(keys.contains("            HotkeyKey.OemPipe => \"\\\\\",\n"));
    assert!(keys.contains("            [\"\\\\\"] = HotkeyKey.OemPipe,\n"));
    assert!(keys.contains("            [\"Ctrl\"] = HotkeyModifiers.Control,\n"));
    // Return's label is its own alias: listed twice, the C# initializer would throw at type init
    assert_eq!(keys.matches("[\"Enter\"]").count(), 1);
    assert!(keys.contains(&format!("public const uint AbiVersion = 0x{:08X}u;", abi_version())));
    assert!(keys.ends_with("    }\n}\n") && !keys.contains('\r'));
    let abi = render_abi();
    assert!(abi.contains("        public const int CH_ERR_STOPPED = -20;\n"));
    assert!(abi.contains("        public uint RawCode;\n        public uint Ch;\n        public uint Flags;\n"));
    assert!(abi.contains("        public int Key;\n"));
}
